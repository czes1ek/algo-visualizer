const Glyph* find(char c) {
    const char upper = static_cast<char>(std::toupper(static_cast<unsigned char>(c)));
    for (const auto& g : kGlyphs) {
        if (g.c == upper) {
            return &g;
        }
    }
    return nullptr;
}

