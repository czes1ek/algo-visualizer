void drawRect(sf::VertexArray& out, float x, float y, float w, float h, sf::Color color) {
    const sf::Vector2f a{x, y};
    const sf::Vector2f b{x + w, y};
    const sf::Vector2f c{x + w, y + h};
    const sf::Vector2f d{x, y + h};
    out.append(sf::Vertex{a, color});
    out.append(sf::Vertex{b, color});
    out.append(sf::Vertex{c, color});
    out.append(sf::Vertex{a, color});
    out.append(sf::Vertex{c, color});
    out.append(sf::Vertex{d, color});
}

float drawText(sf::VertexArray& out, std::string_view text, float x, float y, float scale, sf::Color color) {
    for (const char ch : text) {
        if (const Glyph* g = find(ch)) {
            for (std::size_t row = 0; row < 7; ++row) {
                const char* bits = g->rows[row];
                for (std::size_t col = 0; col < 5; ++col) {
                    if (bits[col] == '#') {
                        drawRect(out, x + static_cast<float>(col) * scale, y + static_cast<float>(row) * scale,
                                 scale, scale, color);
                    }
                }
            }
        }
        x += (kGlyphW + 1.f) * scale;
    }
    return x;
}

